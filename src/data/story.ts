/** How each speaker is labelled on their pop-up (the English name also picks the voice). */
export const SPEAKER_NAMES: Record<string, Text> = {
  'Ms. Moza': t('Ms. Moza · mentor', 'الأستاذة موزة · المرشدة'),
  'Mr. Rashid': t('Mr. Rashid', 'الأستاذ راشد'),
  'Mr. Hamad': t('Mr. Hamad', 'الأستاذ حمد'),
  'Ms. Sara': t('Sara', 'سارة'),
  'Mr. Jasim': t('Mr. Jasim · principal', 'الأستاذ جاسم · المدير'),
};

export function storyFor(worldId: string, kind: 'open' | 'close'): Story | undefined {
  return STORIES.find((c) => c.worldId === worldId && c.kind === kind);
}

export function storyById(id: string): Story | undefined {
  return STORIES.find((c) => c.id === id);
}

/** Where a shot's still lives (relative to BASE_URL). */
export function shotImage(worldId: string, shotId: string): string {
  return `story/${worldId}/${shotId}.jpg`;
}
