/**
 * THE STORY — a short film made of pictures, between worlds. Content, not code.
 *
 * Through-line: Toki's first term as a coach. His mentor, Ms. Moza,
 * gives him an empty notebook and one rule: "Don't write what you see.
 * Write what they learn." Each world teaches him one lens (busy is not
 * learning; a test is a question for the teacher; technology should make
 * thinking louder; feedback works when students act on it; questions need
 * thinking time; different is not the same as differentiated; sometimes
 * the finding is "nothing is wrong"). The Final World is the Master DLIS
 * visit: a whole school, every lens at once.
 *
 * Each shot is one full-screen still with slow camera motion. The
 * narrator reads `narration`; a `quote` pops up near the speaker and is
 * spoken in that person's voice (voice slots from src/audio/voiceKey.ts,
 * rendered by the main audio workflow). Stills live at
 * public/story/<worldId>/<shotId>.jpg (portrait, generated by
 * tools/art/story.py from `prompt` + the art bible preamble); stills carry
 * no text, so both languages work. A missing still shows an illustrated
 * placeholder.
 */

export type Speaker = 'toki' | 'mentor' | 'teacher' | 'student' | 'leader';

export interface StoryQuote {
  who: Speaker;
  /** Display + voice name in English ("Ms. Moza") — picks the voice slot; absent for Toki. */
  name?: string;
  text: Text;
  /** Where the pop-up sits on screen. */
  at?: 'left' | 'right';
}

export interface StoryShot {
  id: string;
  narration: Text;
  quote?: StoryQuote;
  /** Scene description for the image model (English; the art preamble is added by the tool). */
  prompt: string;
  /** Camera move for the still. */
  move?: 'in' | 'out' | 'left' | 'right' | 'up';
}

export interface Story {
  id: string;
  worldId: string;
  kind: 'open' | 'close';
  shots: StoryShot[];
}

